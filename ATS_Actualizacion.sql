-- LinkNoDin ATS: notes, private messages, application history and row policies.
-- Run this once in Supabase SQL Editor before enabling the ATS tools.

begin;

create table if not exists public.application_internal_notes (
    id bigint generated by default as identity primary key,
    application_id integer not null unique references public.applications(id) on delete cascade,
    company_id integer not null references public.companies(id) on delete cascade,
    note text not null default '',
    rating smallint,
    updated_by integer references public.users(id) on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint application_internal_notes_rating_check check (rating is null or rating between 1 and 5),
    constraint application_internal_notes_length_check check (char_length(note) <= 5000)
);

create table if not exists public.application_messages (
    id bigint generated by default as identity primary key,
    application_id integer not null references public.applications(id) on delete cascade,
    sender_user_id integer not null references public.users(id) on delete cascade,
    body text not null,
    read_at timestamptz,
    created_at timestamptz not null default now(),
    constraint application_messages_body_check check (char_length(trim(body)) between 1 and 4000)
);

create index if not exists application_messages_thread_idx
    on public.application_messages(application_id, created_at);
create index if not exists application_history_thread_idx
    on public.application_status_history(application_id, changed_at);

alter table public.application_internal_notes enable row level security;
alter table public.application_messages enable row level security;
alter table public.application_status_history enable row level security;

drop policy if exists application_internal_notes_company_access on public.application_internal_notes;
create policy application_internal_notes_company_access
on public.application_internal_notes
for all to authenticated
using (
    exists (
        select 1 from public.companies c
        join public.users u on u.id = c.user_id
        join public.applications a on a.id = application_internal_notes.application_id
        join public.jobs j on j.id = a.job_id and j.company_id = c.id
        where u.auth_user_id = auth.uid() and c.id = application_internal_notes.company_id
    )
)
with check (
    exists (
        select 1 from public.companies c
        join public.users u on u.id = c.user_id
        join public.applications a on a.id = application_internal_notes.application_id
        join public.jobs j on j.id = a.job_id and j.company_id = c.id
        where u.auth_user_id = auth.uid()
          and c.id = application_internal_notes.company_id
          and application_internal_notes.updated_by = u.id
    )
);

drop policy if exists application_messages_participant_read on public.application_messages;
create policy application_messages_participant_read
on public.application_messages
for select to authenticated
using (
    exists (
        select 1 from public.applications a
        join public.jobs j on j.id = a.job_id
        join public.companies c on c.id = j.company_id
        where a.id = application_messages.application_id
          and (
              c.user_id = (select u.id from public.users u where u.auth_user_id = auth.uid())
              or a.candidate_id = (select u.id from public.users u where u.auth_user_id = auth.uid())
          )
    )
);

drop policy if exists application_messages_participant_insert on public.application_messages;
create policy application_messages_participant_insert
on public.application_messages
for insert to authenticated
with check (
    sender_user_id = (select u.id from public.users u where u.auth_user_id = auth.uid())
    and exists (
        select 1 from public.applications a
        join public.jobs j on j.id = a.job_id
        join public.companies c on c.id = j.company_id
        where a.id = application_messages.application_id
          and (
              c.user_id = (select u.id from public.users u where u.auth_user_id = auth.uid())
              or a.candidate_id = (select u.id from public.users u where u.auth_user_id = auth.uid())
          )
    )
);

drop policy if exists application_messages_participant_update on public.application_messages;
create policy application_messages_participant_update
on public.application_messages
for update to authenticated
using (
    exists (
        select 1 from public.applications a
        join public.jobs j on j.id = a.job_id
        join public.companies c on c.id = j.company_id
        where a.id = application_messages.application_id
          and (
              c.user_id = (select u.id from public.users u where u.auth_user_id = auth.uid())
              or a.candidate_id = (select u.id from public.users u where u.auth_user_id = auth.uid())
          )
    )
)
with check (
    exists (
        select 1 from public.applications a
        join public.jobs j on j.id = a.job_id
        join public.companies c on c.id = j.company_id
        where a.id = application_messages.application_id
          and (
              c.user_id = (select u.id from public.users u where u.auth_user_id = auth.uid())
              or a.candidate_id = (select u.id from public.users u where u.auth_user_id = auth.uid())
          )
    )
);

drop policy if exists application_history_participant_read on public.application_status_history;
create policy application_history_participant_read
on public.application_status_history
for select to authenticated
using (
    exists (
        select 1 from public.applications a
        join public.jobs j on j.id = a.job_id
        join public.companies c on c.id = j.company_id
        where a.id = application_status_history.application_id
          and (
              c.user_id = (select u.id from public.users u where u.auth_user_id = auth.uid())
              or a.candidate_id = (select u.id from public.users u where u.auth_user_id = auth.uid())
          )
    )
);

drop policy if exists application_history_company_insert on public.application_status_history;
create policy application_history_company_insert
on public.application_status_history
for insert to authenticated
with check (
    changed_by = (select u.id from public.users u where u.auth_user_id = auth.uid())
    and exists (
        select 1 from public.applications a
        join public.jobs j on j.id = a.job_id
        join public.companies c on c.id = j.company_id
        where a.id = application_status_history.application_id
          and c.user_id = (select u.id from public.users u where u.auth_user_id = auth.uid())
    )
);

grant select, insert, update on public.application_internal_notes to authenticated;
grant select, insert on public.application_messages to authenticated;
revoke update on public.application_messages from authenticated;
grant update (read_at) on public.application_messages to authenticated;
grant select, insert on public.application_status_history to authenticated;
grant usage, select on sequence public.application_internal_notes_id_seq to authenticated;
grant usage, select on sequence public.application_messages_id_seq to authenticated;

-- Backfill the initial step for existing applications.
insert into public.application_status_history(application_id, changed_by, status, note, changed_at)
select a.id, null, a.status, 'Postulación recibida', a.applied_at
from public.applications a
where not exists (
    select 1 from public.application_status_history h where h.application_id = a.id
);

commit;
